// Builds docs/accessibility/SUMMARY.md from the raw JSON the audit harness saved.
// Every number is read back from those files; nothing is estimated.
import { readdirSync, readFileSync, existsSync, writeFileSync } from "node:fs";
import path from "node:path";

const arg = (n, d) => {
  const i = process.argv.indexOf(`--${n}`);
  return i > -1 ? process.argv[i + 1] : d;
};
const ROOT = path.resolve(arg("root", "../docs/accessibility"));
const SEV = ["critical", "serious", "moderate", "minor"];

const readJson = (dir, file) => {
  const p = path.join(ROOT, dir, file);
  return existsSync(p) ? JSON.parse(readFileSync(p, "utf8")) : null;
};

function collect(dir) {
  const full = path.join(ROOT, dir);
  if (!existsSync(full)) return null;
  const meta = readJson(dir, "meta.json");
  const rows = [];
  for (const f of readdirSync(full).filter((x) => x.startsWith("axe-")).sort()) {
    const key = f.replace(/^axe-/, "").replace(/\.json$/, "");
    const [vp] = key.split("-").slice(-1);
    const id = key.slice(0, -(vp.length + 1));
    const axe = readJson(dir, f);
    const lh = readJson(dir, `lighthouse-${key}.json`);
    const layout = readJson(dir, `layout-${key}.json`);
    const sev = Object.fromEntries(SEV.map((s) => [s, { rules: 0, nodes: 0 }]));
    for (const v of axe.violations) {
      const s = v.impact ?? "minor";
      sev[s].rules += 1;
      sev[s].nodes += v.nodes.length;
    }
    let lhScore = null,
      lhFailed = null;
    if (lh) {
      const cat = lh.categories.accessibility;
      lhScore = cat.score === null ? null : Math.round(cat.score * 100);
      const ids = new Set(cat.auditRefs.map((r) => r.id));
      lhFailed = Object.entries(lh.audits).filter(([k, a]) => ids.has(k) && a.score === 0).length;
    }
    rows.push({
      key,
      id,
      vp,
      label: meta?.pages.find((p) => p.id === id)?.label ?? id,
      sev,
      rules: axe.violations.length,
      nodes: axe.violations.reduce((n, v) => n + v.nodes.length, 0),
      ruleIds: axe.violations.map((v) => `${v.id} (${v.impact}, ${v.nodes.length})`),
      lhScore,
      lhFailed,
      layout,
    });
  }
  return { meta, rows };
}

const before = collect("before");
const after = collect("after");

const cell = (r) => SEV.map((s) => `${r.sev[s].rules}/${r.sev[s].nodes}`).join(" · ");
const lh = (r) => (r && r.lhScore !== null ? `${r.lhScore}` : "n/a (axe-only state)");

let md = `# Accessibility audit summary\n\n`;
md += `Generated by \`frontend/a11y/summarize.mjs\` from the raw JSON in \`before/\` and \`after/\`. Every figure below is read from tool output; none is estimated.\n\n`;
md += `**How to read it.** *axe* counts are \`rules / affected elements\` per severity (critical · serious · moderate · minor), limited to the WCAG 2.0/2.1 A and AA rule tags. *Lighthouse* is the accessibility category score (0 to 100) with the number of failed audits; it reports no severity levels, so none is shown for it. States that need a click first (open dialogs, expanded rows, the mobile drawer) are checked with axe only, because Lighthouse's navigation mode cannot open them. Layout columns come from a small custom script (\`a11y/audit.mjs\`), not from axe or Lighthouse.\n\n`;

if (before) {
  const m = before.meta;
  md += `Tools: Lighthouse ${m.tools.lighthouse}, axe-core ${m.tools.axeCore}, Playwright ${m.tools.playwright}, Chromium ${m.tools.chromium}. Target: production build served locally against the local API with the synthetic demo data.\n\n`;
}

const keys = [...new Set([...(before?.rows ?? []), ...(after?.rows ?? [])].map((r) => r.key))];
const order = (k) => {
  const [vp] = k.split("-").slice(-1);
  return [k.slice(0, -(vp.length + 1)), vp === "1280" ? 0 : 1];
};
keys.sort((a, b) => {
  const [ai, av] = order(a),
    [bi, bv] = order(b);
  return ai === bi ? av - bv : 0;
});

md += `## Before vs after\n\n`;
md += `| Page / state | Width | Lighthouse before | Lighthouse after | axe before (rules/elements) | axe after (rules/elements) |\n|---|---|---|---|---|---|\n`;
for (const k of keys) {
  const b = before?.rows.find((r) => r.key === k);
  const a = after?.rows.find((r) => r.key === k);
  const r = b ?? a;
  const f = (x) => (x ? `${x.lhScore !== null ? `${x.lhScore} (${x.lhFailed} failed)` : "n/a"}` : "not run");
  const ax = (x) => (x ? `${x.rules} / ${x.nodes}` : "not run");
  md += `| ${r.label} | ${r.vp}px | ${f(b)} | ${f(a)} | ${ax(b)} | ${ax(a)} |\n`;
}

for (const [name, set] of [["Before", before], ["After", after]]) {
  if (!set) continue;
  md += `\n## ${name}: axe violations by severity\n\nCells are \`rules/elements\` for critical · serious · moderate · minor.\n\n`;
  md += `| Page / state | Width | critical · serious · moderate · minor | Rules hit |\n|---|---|---|---|\n`;
  for (const k of keys) {
    const r = set.rows.find((x) => x.key === k);
    if (!r) continue;
    md += `| ${r.label} | ${r.vp}px | ${cell(r)} | ${r.ruleIds.join(", ") || "none"} |\n`;
  }
}

for (const [name, set] of [["Before", before], ["After", after]]) {
  if (!set) continue;
  md += `\n## ${name}: layout checks (custom script)\n\n`;
  md += `\`Doc overflow\` is the document's horizontal overflow in CSS px (0 means none). \`Targets < 44px\` counts visible links, buttons and form controls under 44x44 CSS px at that width.\n\n`;
  md += `| Page / state | Width | Doc overflow px | Targets < 44px |\n|---|---|---|---|\n`;
  for (const k of keys) {
    const r = set.rows.find((x) => x.key === k);
    if (!r || !r.layout) continue;
    md += `| ${r.label} | ${r.vp}px | ${r.layout.documentOverflowPx} | ${r.layout.targetsUnder44px} |\n`;
  }
  if (set.meta?.reflow) {
    md += `\nReflow (document horizontal overflow in px; 640px viewport is the same layout width as 200% zoom on a 1280px screen):\n\n| Page | 640px | 375px | 320px |\n|---|---|---|---|\n`;
    for (const [id, v] of Object.entries(set.meta.reflow)) {
      md += `| ${id} | ${v[640].documentOverflowPx} | ${v[375].documentOverflowPx} | ${v[320].documentOverflowPx} |\n`;
    }
  }
}

writeFileSync(path.join(ROOT, "SUMMARY.md"), md);
console.log(`wrote ${path.join(ROOT, "SUMMARY.md")}`);
